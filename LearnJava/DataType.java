public class DataType {
    public static void main(String[] args){

        // Integer Data Type
        byte num1 =10;            // 1 byte range = -128 to 127
        short num3 = 40;          // 2 byte range = -32768 to 32767
        int num2 = 1000000000;    // 4 byte range = -2147483648 to 2147483647
        long num4 = 50202020000l; // 8 byte range = -9223372036854775808 to 9223372036854775807
        
         // float
        float num5 = 20.5f;
        double num6 =30.56454524526;
        
        //character
        char grade = 'A';         // 2 byte range = 0 t0 65535

        //boolean
        boolean value = true;

        // printing 
        System.out.println("byte value is  " );  
        System.out.println(num1);  

        System.out.println();

        System.out.println("short value is  ");
        System.out.println(num3);

        System.out.println();

        System.out.println("int value is  ");
        System.out.println(num2);

        System.out.println();


        System.out.println("long value is  ");
        System.out.println(num4);

        System.out.println();

        System.out.println("float value is  ");
        System.out.println(num5);
        System.out.println();

        System.out.println("double value is  ");
        System.out.println(num6);

        System.out.println();

        

        System.out.println("char value is  ");
        System.out.println(grade);

        System.out.println();

        System.out.println("boolean value is  ");
        System.out.println(value);

        


    }
}
